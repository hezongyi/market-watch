await new Promise(r=>setTimeout(r,3200));
await state.page.getByRole('button',{name:'暂停背景动画',exact:true}).click();
await state.page.mouse.move(20,850);
await new Promise(r=>setTimeout(r,2200));
await state.page.getByRole('button',{name:'开启背景动画',exact:true}).click();
await state.page.getByRole('button',{name:'切换浅色主题',exact:true}).click();
await state.page.getByLabel('管理员密码',{exact:true}).fill('');
