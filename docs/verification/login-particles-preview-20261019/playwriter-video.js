const fs=require('node:fs');
fs.mkdirSync('/tmp/mw-login-particles-frames',{recursive:true});
await state.page.bringToFront();
await state.page.setViewportSize({width:1440,height:900});
await state.page.getByLabel('管理员密码',{exact:true}).fill('');
await state.page.mouse.move(20,850);
await ghostCursor.hide({page:state.page});
state.videoFrames=[];
state.videoCDP=await getCDPSession({page:state.page});
state.videoFrameHandler=async event=>{
 const i=state.videoFrames.length;
 const path='/tmp/mw-login-particles-frames/'+String(i).padStart(5,'0')+'.jpg';
 fs.writeFileSync(path,Buffer.from(event.data,'base64'));
 state.videoFrames.push({path,timestamp:event.metadata.timestamp});
 await state.videoCDP.send('Page.screencastFrameAck',{sessionId:event.sessionId});
};
state.videoCDP.on('Page.screencastFrame',state.videoFrameHandler);
await state.videoCDP.send('Page.startScreencast',{format:'jpeg',quality:92,maxWidth:1440,maxHeight:900,everyNthFrame:1});
await new Promise(r=>setTimeout(r,5000));
