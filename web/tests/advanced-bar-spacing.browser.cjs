// Regression: XAUUSD D1 switching must preserve user bar spacing.
// Requires the local acceptance Compose stack; self-signed TLS is test-only.
const { chromium } = require("playwright");
const fs = require("node:fs");
const assert = require("node:assert/strict");
(async () => {
  const browser = await chromium.launch({
    headless: true,
    executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,
  });
  const page = await browser.newPage({
    ignoreHTTPSErrors: true,
    viewport: { width: 1600, height: 950 },
  });
  await page.route(/\/api\/(market-data\/history|charts\/data)$/, (route) => {
    const body = route.request().postDataJSON();
    return route.continue({
      postData: JSON.stringify({
        ...body,
        before: Math.min(body.before || 1790622000000, 1790622000000),
      }),
    });
  });
  await page.goto("https://localhost:15443/");
  await page
    .getByLabel("管理员密码")
    .fill(
      JSON.parse(
        fs.readFileSync("../../market-watch/artifacts/local-credentials.json"),
      ).password,
    );
  const login = page.waitForResponse(
    (r) => r.url().endsWith("/api/login") && r.request().method() === "POST",
  );
  await page.getByRole("button", { name: "登录工作台" }).click();
  assert.equal((await login).status(), 200);
  await page.evaluate(async () => {
    const session = await (await fetch("/api/session")).json();
    const response = await fetch("/api/advanced-charts/workspaces", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": session.csrf,
      },
      body: JSON.stringify({ name: "XAUUSD周期柱宽回归" }),
    });
    if (!response.ok)
      throw Error("Workspace creation failed " + response.status);
  });
  await page.goto("https://localhost:15443/advanced-charts");
  await page
    .locator('iframe[title="专业图表工作区"]')
    .waitFor({ timeout: 30000 });
  await page.waitForTimeout(15000);
  const frame = page
    .frames()
    .find((f) => f.url().startsWith("https://127.0.0.1:15444/"));
  assert.ok(frame, "isolated HTTPS chart frame must load");
  await frame.waitForFunction(
    () => ready && !loading && widget.activeChart().dataReady(),
    null,
    { timeout: 60000 },
  );
  await frame.evaluate(async () => {
    widget.dateRangeSync().setValue(false);
    await widget.activeChart().setSymbol('XAUUSD');
    await widget.activeChart().setResolution('60');
    widget.activeChart().getTimeScale().setBarSpacing(6);
  });
  for (const resolution of ['1D', '60', '240', '1D', '5']) {
    await frame.evaluate(r => widget.activeChart().setResolution(r), resolution);
    await frame.waitForFunction(() => widget.activeChart().dataReady() && !rangeGuard.busy(), null, {timeout:60000});
    await page.waitForTimeout(1500);
    const spacing = await frame.evaluate(() => widget.activeChart().getTimeScale().barSpacing());
    console.log(JSON.stringify({resolution, spacing}));
    assert.ok(Math.abs(spacing - 6) < 0.1, `Spacing changed on ${resolution}: ${spacing}`);
  }
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
