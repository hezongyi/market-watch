import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({executablePath:'/home/quant/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const watchName='浏览器验收 · '+Date.now();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto((process.env.TEST_BASE_URL || 'http://127.0.0.1:5173'));
await page.getByLabel('管理员密码').fill(JSON.parse(fs.readFileSync('../artifacts/local-credentials.json','utf8')).password);
await page.getByRole('button',{name:'登录工作台'}).click();
await page.getByRole('heading',{name:'让机会，主动找到你。'}).waitFor();
await page.screenshot({path:'../artifacts/dashboard-desktop.png',fullPage:true});
await page.getByRole('button',{name:'新建预警',exact:true}).click();
await page.getByLabel('预警名称').fill(watchName);
await page.getByRole('button',{name:'开启监控',exact:true}).click();
const watch=page.locator('article').filter({has:page.getByText(watchName,{exact:true})});
await watch.waitFor();
await watch.getByRole('button',{name:'取消监控'}).click();
await watch.getByText('已取消',{exact:true}).waitFor();
await page.getByRole('link',{name:'历史演练'}).click();
await page.getByRole('heading',{name:'回到当时，验证你的判断。'}).waitFor();
await page.getByRole('link',{name:'提醒与设置'}).click();
await page.getByRole('heading',{name:'让重要提醒，真正被听见。'}).waitFor();
await page.getByText('使用 ntfy 原生应用。铃声与持续响铃行为在手机端设置。').waitFor();
if(await page.getByRole('button',{name:'生成配对令牌'}).count())throw new Error('Retired companion pairing remains visible');
await page.getByRole('button',{name:'保存提醒设置'}).click();
await page.getByText('提醒设置已保存',{exact:true}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.getByRole('link',{name:'行情与监控'}).click();
await page.screenshot({path:'../artifacts/dashboard-mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
await browser.close();
console.log(JSON.stringify({pageErrors:errors,mobileOverflow:overflow,flows:['login','create-watch','cancel-watch','replay-route','settings-route','mobile-layout']}));
if(errors.length||overflow)process.exit(1);
